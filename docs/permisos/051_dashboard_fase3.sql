DECLARE
    FUNCTION norm(p VARCHAR2) RETURN VARCHAR2 IS
    BEGIN
        RETURN TRIM(REGEXP_REPLACE(TRANSLATE(UPPER(p), 'ÁÉÍÓÚÜÑ', 'AEIOUUN'), '[^A-Z ]', ' '));
    END;
    -- true si TODAS las palabras (de 2+ letras) del nombre del usuario estan en el nombre de la lista
    FUNCTION cruza(p_usuario VARCHAR2, p_lista VARCHAR2) RETURN BOOLEAN IS
        v_lista VARCHAR2(300) := ' ' || REGEXP_REPLACE(norm(p_lista), ' +', ' ') || ' ';
        v_nom   VARCHAR2(300) := REGEXP_REPLACE(norm(p_usuario), ' +', ' ');
        v_tok   VARCHAR2(60);
        v_i     PLS_INTEGER := 1;
        v_n     PLS_INTEGER := 0;
    BEGIN
        LOOP
            v_tok := REGEXP_SUBSTR(v_nom, '[^ ]+', 1, v_i);
            EXIT WHEN v_tok IS NULL;
            IF LENGTH(v_tok) >= 2 THEN
                v_n := v_n + 1;
                IF INSTR(v_lista, ' ' || v_tok || ' ') = 0 THEN RETURN FALSE; END IF;
            END IF;
            v_i := v_i + 1;
        END LOOP;
        RETURN v_n >= 2;
    END;
BEGIN
    FOR r IN (SELECT ROWID rid, NOMBRE_COMPLETO, MES, DIA FROM CUMPLE_CARGA WHERE RESULTADO IS NULL) LOOP
        DECLARE
            v_cnt PLS_INTEGER := 0;
            v_id  NUMBER;
        BEGIN
            FOR u IN (SELECT IDUSUARIO, NOMBRE || ' ' || APELLIDOS AS NOM FROM USUARIO WHERE ESTADO = 'a') LOOP
                IF cruza(u.NOM, r.NOMBRE_COMPLETO) THEN v_cnt := v_cnt + 1; v_id := u.IDUSUARIO; END IF;
            END LOOP;
            IF v_cnt = 1 THEN
                MERGE INTO USUARIO_CUMPLE c USING (SELECT v_id AS ID FROM DUAL) s ON (c.ID_USUARIO = s.ID)
                WHEN MATCHED THEN UPDATE SET c.MES = r.MES, c.DIA = r.DIA
                WHEN NOT MATCHED THEN INSERT (ID_USUARIO, MES, DIA) VALUES (v_id, r.MES, r.DIA);
                UPDATE CUMPLE_CARGA SET RESULTADO = 'OK usuario ' || v_id WHERE ROWID = r.rid;
            ELSIF v_cnt = 0 THEN
                UPDATE CUMPLE_CARGA SET RESULTADO = 'SIN COINCIDENCIA' WHERE ROWID = r.rid;
            ELSE
                UPDATE CUMPLE_CARGA SET RESULTADO = 'AMBIGUO (' || v_cnt || ' usuarios)' WHERE ROWID = r.rid;
            END IF;
        END;
    END LOOP;
    COMMIT;
END;
