-- Pendientes de completar a mano (sin coincidencia o ambiguos)
SELECT NOMBRE_COMPLETO, MES, DIA, RESULTADO FROM CUMPLE_CARGA WHERE RESULTADO NOT LIKE 'OK%' ORDER BY NOMBRE_COMPLETO;
-- Usuarios activos que quedaron sin cumpleanos (para completarlos en la pantalla nueva)
SELECT u.USUARIO, u.NOMBRE, u.APELLIDOS FROM USUARIO u
 WHERE u.ESTADO = 'a' AND NOT EXISTS (SELECT 1 FROM USUARIO_CUMPLE c WHERE c.ID_USUARIO = u.IDUSUARIO) ORDER BY 3, 2;

