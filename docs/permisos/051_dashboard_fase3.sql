-- 3) Novedades ----------------------------------------------------------------------
CREATE TABLE APP_NOVEDAD (
    ID_NOVEDAD  NUMBER NOT NULL,
    TITULO      VARCHAR2(120) NOT NULL,
    TEXTO       VARCHAR2(1000),
    FECHA_DESDE DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    FECHA_HASTA DATE,                            -- null = sin vencimiento
    ESTADO      CHAR(1) DEFAULT 'A' NOT NULL,     -- A activa, I inactiva
    ID_USUARIO  NUMBER,                           -- quien la publico
    FECHA_CREA  DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_APP_NOVEDAD PRIMARY KEY (ID_NOVEDAD)
);

-- 4) Permiso -----------------------------------------------------------------------------
INSERT INTO APP_PERMISO (ID_PERMISO, CODIGO, MODULO, DESCRIPCION, ESTADO)
    SELECT NVL(MAX(ID_PERMISO), 0) + 1, 'NOVEDADES_GESTIONAR', 'PROYECTOS',
           'Publicar y retirar novedades (avisos) que se muestran en el dashboard', 'A'
    FROM APP_PERMISO WHERE NOT EXISTS (SELECT 1 FROM APP_PERMISO WHERE CODIGO = 'NOVEDADES_GESTIONAR');

MERGE INTO APP_USUARIO_PERMISO up
USING (SELECT u.IDUSUARIO, p.ID_PERMISO FROM USUARIO u, APP_PERMISO p
       WHERE UPPER(u.USUARIO) = 'JVARAS' AND p.CODIGO = 'NOVEDADES_GESTIONAR') src
ON (up.IDUSUARIO = src.IDUSUARIO AND up.ID_PERMISO = src.ID_PERMISO)
WHEN NOT MATCHED THEN INSERT (IDUSUARIO, ID_PERMISO, TIPO) VALUES (src.IDUSUARIO, src.ID_PERMISO, 'G');
COMMIT;

