-- =====================================================================
-- Modulo de Solicitud de Vacaciones -- carga masiva de cedula y
-- empresa de afiliacion IESS desde PATRONAL_AE_2.xlsx (36 empleados,
-- 10 empresas patronales).
--
-- REQUIERE haber corrido antes:
--   024_vacaciones_cedula.sql          (columna CEDULA)
--   025_vacaciones_empresa_iess.sql    (columna EMPRESA_IESS)
--
-- COMO SE ARMO EL MATCH: el excel no trae ID_USUARIO, asi que cada
-- MERGE busca al empleado por nombre completo, comparando
-- APELLIDOS||' '||NOMBRE contra el texto del excel (el excel viene en
-- orden "apellidos nombres", al reves de como esta pantalla arma
-- u.NOMBRE||' '||u.APELLIDOS). Si el nombre no calza exactamente con
-- lo que hay en USUARIO (tilde distinta, orden distinto, empleado no
-- existe en el sistema, etc.) el MERGE simplemente no hace nada para
-- esa fila -- no falla, pero tampoco avisa. Por eso el SELECT de
-- verificacion al final es obligatorio: compara cuantos de los 36
-- quedaron cargados contra cuantos se esperaba.
--
-- CASO ESPECIAL: PARRALES SOLIS UKLES XAVIER aparece en el excel dos
-- veces, con dos empresas distintas (BUSINESS ADVISOR NETWORK BUADNET
-- S.A. con aviso de entrada 01/08/2025, y ARTHURS AUDIT GLOBAL
-- HURSDIT S.A. con aviso de entrada 15/07/2024). Se asumio que la
-- empresa vigente es la del aviso MAS RECIENTE (BUADNET) y por eso es
-- la unica que se carga aqui. Si esto no es correcto (por ejemplo si
-- en realidad sigue afiliado a HURSDIT, o esta afiliado a ambas),
-- avisar para corregir el registro manualmente en la pantalla de
-- Configuracion.
-- =====================================================================

-- Varios nombres de empresa traen '&' (BUADNET TAX&FINANCE, KAVODLEX
-- LEGAL & CORPORATE...). SQL*Plus / SQL Developer interpretan eso como
-- el inicio de una variable de sustitucion y detienen el script
-- pidiendo un valor -- SET DEFINE OFF lo desactiva para que el '&' se
-- guarde tal cual, como texto literal.
SET DEFINE OFF;

