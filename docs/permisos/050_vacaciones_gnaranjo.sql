-- =====================================================================
-- GNARANJO: acceso al modulo de Vacaciones (igual que DNARANJO / SMORAN).
--
-- Se le dan los permisos VACACIONES_CONFIGURAR y VACACIONES_GESTIONAR y se la agrega como gestora del grupo
-- KENNEDY (junto a smoran y dnaranjo). Si debe gestionar otro grupo, cambiar 'KENNEDY' abajo
-- (grupos: ROMERIA, KENNEDY). Ejecutar DESPUES del 044. Luego cerrar sesion y volver a entrar.
-- =====================================================================
INSERT INTO VAC_GRUPO_GESTOR (ID_GRUPO, ID_USUARIO)
    SELECT g.ID_GRUPO, u.IDUSUARIO FROM VAC_GRUPO g, USUARIO u
    WHERE g.NOMBRE = 'KENNEDY' AND UPPER(u.USUARIO) = 'GNARANJO'
      AND NOT EXISTS (SELECT 1 FROM VAC_GRUPO_GESTOR x WHERE x.ID_GRUPO = g.ID_GRUPO AND x.ID_USUARIO = u.IDUSUARIO);

MERGE INTO APP_USUARIO_PERMISO up
USING (SELECT u.IDUSUARIO, p.ID_PERMISO FROM USUARIO u, APP_PERMISO p
       WHERE UPPER(u.USUARIO) = 'GNARANJO' AND p.CODIGO IN ('VACACIONES_CONFIGURAR', 'VACACIONES_GESTIONAR')) src
ON (up.IDUSUARIO = src.IDUSUARIO AND up.ID_PERMISO = src.ID_PERMISO)
WHEN MATCHED THEN UPDATE SET up.TIPO = 'G'
WHEN NOT MATCHED THEN INSERT (IDUSUARIO, ID_PERMISO, TIPO) VALUES (src.IDUSUARIO, src.ID_PERMISO, 'G');
COMMIT;

-- Verificacion
SELECT g.NOMBRE AS GRUPO, u.USUARIO AS GESTOR FROM VAC_GRUPO_GESTOR gg
JOIN VAC_GRUPO g ON g.ID_GRUPO = gg.ID_GRUPO JOIN USUARIO u ON u.IDUSUARIO = gg.ID_USUARIO ORDER BY 1, 2;
SELECT u.USUARIO, p.CODIGO, up.TIPO FROM APP_USUARIO_PERMISO up JOIN USUARIO u ON u.IDUSUARIO = up.IDUSUARIO
JOIN APP_PERMISO p ON p.ID_PERMISO = up.ID_PERMISO WHERE UPPER(u.USUARIO) = 'GNARANJO' AND p.CODIGO LIKE 'VACACIONES%';
SELECT USUARIO, NOMBRE, APELLIDOS FROM USUARIO WHERE UPPER(USUARIO) = 'GNARANJO';
