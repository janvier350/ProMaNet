-- =====================================================================
-- ProMaNet - Base de datos MySQL (para MySQL Workbench 8.0.16 o superior)
-- Generado a partir de la estructura Oracle vigente del proyecto:
--   docs/migracion/atp_01_estructura.sql + atp_02_llaves_foraneas.sql
--   + scripts de modulos (permisos 001-042, capacitaciones, legal,
--     perifericos, ajuste de stock de suministros).
--
-- Como usarlo en MySQL Workbench:
--   1) File > Open SQL Script... > este archivo, y ejecutar todo (rayo).
--   2) Para obtener el diagrama E-R: Database > Reverse Engineer...
--      (conexion, esquema "promanet", siguiente hasta terminar).
--   3) Opcional: ejecutar despues promanet_mysql_02_relaciones_logicas.sql
--      para agregar las relaciones (llaves foraneas) que el modelo implica
--      pero que la base Oracle real no declara.
--
-- Convenciones de la conversion Oracle -> MySQL:
--   * NUMBER -> INT (ids), DECIMAL (dias, montos); DATE -> DATETIME;
--     VARCHAR2 -> VARCHAR; FLOAT(126) de dinero -> DECIMAL(12,2); BLOB -> LONGBLOB.
--   * SYSDATE -> CURRENT_TIMESTAMP. Los ids que la aplicacion calcula con
--     MAX+1 siguen funcionando: las llaves numericas son AUTO_INCREMENT y
--     aceptan valores explicitos.
--   * Tablas Oracle sin llave primaria reciben una PK sobre su primera
--     columna (ver lista al final).
-- =====================================================================

